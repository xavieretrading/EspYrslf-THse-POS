    branch_id BIGINT PRIMARY KEY REFERENCES public.branches(id),
    total_sales NUMERIC(20, 2) NOT NULL DEFAULT 0.00,
    total_receipts BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

