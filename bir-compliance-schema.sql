-- 3. Create Store Credits table
CREATE TABLE IF NOT EXISTS public.store_credits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT REFERENCES public.branches(id) DEFAULT 1,
    amount REAL NOT NULL,
    status TEXT DEFAULT 'active', -- active, used, void
    issued_to TEXT,
    reference_order_id BIGINT REFERENCES public.orders(id),
    used_on_order_id BIGINT REFERENCES public.orders(id),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create Grand Accumulating Total (GAT) table
-- This must never be reset and should hold at least 12 digits. 
-- Using NUMERIC(20, 2) to ensure it can hold very large numbers accurately.
